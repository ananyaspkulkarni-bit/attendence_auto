"""Report generator module for AttendEase preview reports."""

from pathlib import Path
from typing import Optional, Union
from attendease.attendance import StudentAttendanceSummary, PeriodAttendance
from attendease.config import ATTENDANCE_THRESHOLD, REPORT_OUTPUT_DIR


def format_period_str(period: PeriodAttendance) -> str:
    """Formats a PeriodAttendance object into a readable display string."""
    if not period.has_data:
        return "No classes held in this period (N/A)"
    
    pct_str = f"{period.attendance_percentage:.2f}%" if period.attendance_percentage is not None else "N/A"
    return (
        f"{pct_str} ({period.classes_attended}/{period.classes_held} attended, "
        f"{period.classes_missed} missed)"
    )


def generate_report_markdown(
    summary: StudentAttendanceSummary,
    threshold: float = ATTENDANCE_THRESHOLD
) -> str:
    """Generates a Markdown formatted attendance report preview.

    Args:
        summary: StudentAttendanceSummary calculated for a student.
        threshold: Required overall percentage threshold (default from config).

    Returns:
        Formatted Markdown text string.
    """
    overall_pct = summary.overall.attendance_percentage
    warning_triggered = (overall_pct is not None) and (overall_pct < threshold)

    lines = []
    lines.append("================================================================================")
    lines.append("                         ATTENDEASE REPORT PREVIEW                              ")
    lines.append("================================================================================")
    lines.append(f"Student Name   : {summary.name}")
    lines.append(f"Student ID     : {summary.student_id}")
    lines.append(f"Student Email  : {summary.email}")
    lines.append(f"Reporting Date : {summary.reporting_date.strftime('%Y-%m-%d')}")
    lines.append("--------------------------------------------------------------------------------")
    lines.append("ATTENDANCE SUMMARY")
    lines.append("--------------------------------------------------------------------------------")
    lines.append(f"• Weekly Attendance  ({summary.weekly.start_date} to {summary.weekly.end_date}):")
    lines.append(f"  {format_period_str(summary.weekly)}")
    lines.append(f"• Monthly Attendance ({summary.monthly.start_date.strftime('%B %Y')}):")
    lines.append(f"  {format_period_str(summary.monthly)}")
    lines.append(f"• Overall Attendance (Up to {summary.reporting_date}):")
    lines.append(f"  {format_period_str(summary.overall)}")
    lines.append("--------------------------------------------------------------------------------")

    if warning_triggered:
        lines.append("⚠️  WARNING: OVERALL ATTENDANCE IS BELOW THE REQUIRED TARGET!")
        lines.append(f"   Current Overall: {overall_pct:.2f}% | Required Minimum: {threshold:.2f}%")
        lines.append("   Action Recommended: Please contact your academic advisor or course instructor.")
        lines.append("--------------------------------------------------------------------------------")
    else:
        lines.append("✅ STATUS: Good Standing")
        lines.append(f"   Current Overall: {overall_pct:.2f}% | Target Minimum: {threshold:.2f}%")
        lines.append("--------------------------------------------------------------------------------")

    lines.append("DISCLAIMER:")
    lines.append("This report is an automated preview generated by AttendEase for informational")
    lines.append("purposes only. It is not an official college attendance record.")
    lines.append("================================================================================")

    return "\n".join(lines)


def save_report_to_file(
    report_text: str,
    student_id: str,
    output_dir: Optional[Union[str, Path]] = None
) -> Path:
    """Saves the report text to a file in the output directory.

    Args:
        report_text: The string report content.
        student_id: ID of student for naming file.
        output_dir: Output directory path (defaults to config REPORT_OUTPUT_DIR).

    Returns:
        Path object pointing to the created report file.
    """
    target_dir = Path(output_dir) if output_dir else REPORT_OUTPUT_DIR
    target_dir.mkdir(parents=True, exist_ok=True)

    filename = f"report_{student_id}.txt"
    filepath = target_dir / filename
    filepath.write_text(report_text, encoding="utf-8")
    return filepath
